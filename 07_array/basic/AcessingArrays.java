package array.basic;

public class AcessingArrays {

    public static void main(String[] args){
        int[] arrsOfNum = {0,1,2,4,3,5,6,7,8,9,10};
        System.out.println(arrsOfNum[arrsOfNum.length-1]);
        System.out.println(arrsOfNum[0]);
        System.out.println(arrsOfNum[5]);
        System.out.println(arrsOfNum[4]);
        System.out.println(arrsOfNum[3]);
    }
}
